"""Tracing models for execution traces and events."""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any
from uuid import UUID, uuid4

from pydantic import BaseModel, Field, model_validator


class TraceEventType(str, Enum):
    """Types of trace events."""

    LLM_CALL = "llm_call"
    LLM_RESPONSE = "llm_response"
    TOOL_CALL = "tool_call"
    TOOL_RESPONSE = "tool_response"
    AGENT_STEP = "agent_step"
    AGENT_ITERATION = "agent_iteration"
    AGENT_DECISION = "agent_decision"
    EXECUTION_START = "execution_start"
    EXECUTION_END = "execution_end"
    ERROR = "error"
    CUSTOM = "custom"

# Stores how many tokens the AI consumed.
class TokenUsage(BaseModel):
    """Token usage for an LLM call.

    Attributes:
        prompt_tokens: Input tokens sent to the model.
        completion_tokens: Output tokens generated by the model.
        cached_tokens: Cached input tokens (e.g., from prompt caching).
        total_tokens: Total tokens (prompt + completion + cached).
    """

    prompt_tokens: int = Field(default=0, ge=0, description="Input/prompt tokens")
    completion_tokens: int = Field(default=0, ge=0, description="Output/completion tokens")
    cached_tokens: int = Field(default=0, ge=0, description="Cached input tokens")
    total_tokens: int = Field(default=0, ge=0, description="Total tokens")

    @model_validator(mode="after")
    def compute_total(self) -> TokenUsage:
        self.total_tokens = (
            self.prompt_tokens + self.completion_tokens + self.cached_tokens
        )
        return self

    def __add__(self, other: TokenUsage) -> TokenUsage:
        return TokenUsage(
            prompt_tokens=self.prompt_tokens + other.prompt_tokens,
            completion_tokens=self.completion_tokens + other.completion_tokens,
            cached_tokens=self.cached_tokens + other.cached_tokens,
        )

    model_config = {
        "validate_assignment": False,
        "extra": "forbid",
    }


class LatencyMetrics(BaseModel):
    """Latency measurements for an operation."""

    start_time: datetime = Field(description="Operation start time")
    end_time: datetime | None = Field(None, description="Operation end time")
    duration_ms: float | None = Field(default=None, ge=0, description="Duration in milliseconds")
    queue_time_ms: float = Field(default=0.0, ge=0, description="Queue/wait time in ms")
    processing_time_ms: float = Field(default=0.0, ge=0, description="Processing time in ms")

    @model_validator(mode="after")
    def compute_duration(self) -> LatencyMetrics:
        if self.start_time and self.end_time:
            self.duration_ms = (self.end_time - self.start_time).total_seconds() * 1000
        return self

    def finalize(self, end_time: datetime | None = None) -> None:
        """Mark the operation as complete."""
        self.end_time = end_time or datetime.now(timezone.utc)
        if self.start_time and self.end_time:
            self.duration_ms = (self.end_time - self.start_time).total_seconds() * 1000

    model_config = {
        "validate_assignment": False,
        "extra": "forbid",
    }


class LatencyStats(BaseModel):
    """Aggregated latency statistics for a set of operations."""

    count: int = Field(default=0, ge=0, description="Number of measured operations")
    min_ms: float | None = Field(default=None, ge=0, description="Minimum latency (ms)")
    max_ms: float | None = Field(default=None, ge=0, description="Maximum latency (ms)")
    avg_ms: float | None = Field(default=None, ge=0, description="Average latency (ms)")
    median_ms: float | None = Field(default=None, ge=0, description="Median latency (ms)")
    p95_ms: float | None = Field(default=None, ge=0, description="95th percentile latency (ms)")

    @classmethod
    def from_durations(cls, durations: list[float]) -> LatencyStats:
        """Create LatencyStats from a list of durations in milliseconds.

        Args:
            durations: List of duration values in milliseconds.

        Returns:
            LatencyStats with computed statistics.
        """
        if not durations:
            return cls()

        valid_durations = [d for d in durations if d is not None and d >= 0]
        if not valid_durations:
            return cls()

        sorted_durations = sorted(valid_durations)
        count = len(sorted_durations)

        def percentile(sorted_vals: list[float], p: float) -> float:
            if not sorted_vals:
                return 0.0
            k = (len(sorted_vals) - 1) * p
            f = int(k)
            c = min(f + 1, len(sorted_vals) - 1)
            if f == c:
                return sorted_vals[f]
            return sorted_vals[f] + (sorted_vals[c] - sorted_vals[f]) * (k - f)

        return cls(
            count=count,
            min_ms=sorted_durations[0],
            max_ms=sorted_durations[-1],
            avg_ms=sum(sorted_durations) / count,
            median_ms=percentile(sorted_durations, 0.5),
            p95_ms=percentile(sorted_durations, 0.95),
        )

    model_config = {
        "validate_assignment": False,
        "extra": "forbid",
    }

# Stores the estimated cost.
class CostEstimate(BaseModel):
    """Estimated cost for an LLM operation.

    Attributes:
        input_cost_usd: Input token cost in USD.
        output_cost_usd: Output token cost in USD.
        total_cost_usd: Total cost in USD.
        model_name: Primary model name (first model added, for back-compat).
        model_names: List of all model names contributing to this cost estimate.
        pricing_version: Primary pricing version (first model's, for back-compat).
        pricing_versions: List of all pricing versions.
    """

    input_cost_usd: float = Field(default=0.0, ge=0, description="Input token cost in USD")
    output_cost_usd: float = Field(default=0.0, ge=0, description="Output token cost in USD")
    total_cost_usd: float = Field(default=0.0, ge=0, description="Total cost in USD")
    model_name: str | None = Field(None, description="Primary model name (first model)")
    model_names: list[str] = Field(default_factory=list, description="All model names")
    pricing_version: str | None = Field(None, description="Primary pricing version")
    pricing_versions: list[str] = Field(default_factory=list, description="All pricing versions")

    @model_validator(mode="after")
    def compute_total(self) -> CostEstimate:
        self.total_cost_usd = self.input_cost_usd + self.output_cost_usd
        return self

    def __add__(self, other: CostEstimate) -> CostEstimate:
        # Combine model names, avoiding duplicates while preserving order
        combined_names = list(self.model_names)
        for name in other.model_names:
            if name and name not in combined_names:
                combined_names.append(name)

        combined_versions = list(self.pricing_versions)
        for ver in other.pricing_versions:
            if ver and ver not in combined_versions:
                combined_versions.append(ver)

        return CostEstimate(
            input_cost_usd=self.input_cost_usd + other.input_cost_usd,
            output_cost_usd=self.output_cost_usd + other.output_cost_usd,
            model_name=self.model_name or other.model_name,
            model_names=combined_names,
            pricing_version=self.pricing_version or other.pricing_version,
            pricing_versions=combined_versions,
        )

    model_config = {
        "validate_assignment": False,
        "extra": "forbid",
    }


class ModelPricing(BaseModel):
    """Pricing configuration for a specific model.

    Attributes:
        model_name: Model identifier (e.g., "gpt-4o", "claude-3-5-sonnet").
        input_price_per_million: Price per 1M input tokens in USD.
        output_price_per_million: Price per 1M output tokens in USD.
        cached_input_price_per_million: Price per 1M cached input tokens in USD.
            If None, cached tokens are priced at input_price_per_million.
        version: Pricing data version for tracking.
    """

    model_name: str = Field(..., min_length=1, description="Model identifier")
    input_price_per_million: float = Field(
        default=0.0, ge=0, description="Price per 1M input tokens (USD)"
    )
    output_price_per_million: float = Field(
        default=0.0, ge=0, description="Price per 1M output tokens (USD)"
    )
    cached_input_price_per_million: float | None = Field(
        default=None, ge=0, description="Price per 1M cached input tokens (USD)"
    )
    version: str | None = Field(None, description="Pricing data version")

    @model_validator(mode="after")
    def validate_prices(self) -> ModelPricing:
        if self.input_price_per_million < 0:
            raise ValueError("input_price_per_million must be non-negative")
        if self.output_price_per_million < 0:
            raise ValueError("output_price_per_million must be non-negative")
        cached_price = self.cached_input_price_per_million
        if cached_price is not None and cached_price < 0:
            raise ValueError("cached_input_price_per_million must be non-negative")
        return self

    def estimate_cost(self, token_usage: TokenUsage) -> CostEstimate:
        """Estimate cost for given token usage.

        Cached tokens are a subset of prompt_tokens, not additional tokens.
        regular_input_tokens = prompt_tokens - cached_tokens

        Args:
            token_usage: Token usage to estimate cost for.

        Returns:
            CostEstimate with input, output, and total costs.
        """
        # Regular (non-cached) input tokens
        regular_input = max(0, token_usage.prompt_tokens - token_usage.cached_tokens)

        # Cached input tokens
        cached_input = token_usage.cached_tokens

        # Output tokens
        output_tokens = token_usage.completion_tokens

        # Calculate costs (prices are per million tokens)
        input_cost = (regular_input / 1_000_000) * self.input_price_per_million
        cached_cost = 0.0
        if cached_input > 0:
            price = (
                self.cached_input_price_per_million
                if self.cached_input_price_per_million is not None
                else self.input_price_per_million
            )
            cached_cost = (cached_input / 1_000_000) * price
        output_cost = (output_tokens / 1_000_000) * self.output_price_per_million

        return CostEstimate(
            input_cost_usd=input_cost + cached_cost,
            output_cost_usd=output_cost,
            total_cost_usd=input_cost + cached_cost + output_cost,
            model_name=self.model_name,
            model_names=[self.model_name] if self.model_name else [],
            pricing_version=self.version,
            pricing_versions=[self.version] if self.version else [],
        )

    model_config = {
        "validate_assignment": True,
        "extra": "forbid",
    }


class ModelPricingRegistry:
    """Registry for model pricing configurations.

    Allows registering and retrieving pricing by model identifier.
    Supports fallback pricing for unknown models.
    """

    def __init__(self) -> None:
        self._pricing: dict[str, ModelPricing] = {}
        self._fallback: ModelPricing | None = None

    def register(self, pricing: ModelPricing) -> None:
        """Register pricing for a model.

        Args:
            pricing: ModelPricing to register.
        """
        self._pricing[pricing.model_name] = pricing

    def unregister(self, model_name: str) -> bool:
        """Unregister pricing for a model.

        Args:
            model_name: Model identifier to remove.

        Returns:
            True if model was registered and removed, False otherwise.
        """
        if model_name in self._pricing:
            del self._pricing[model_name]
            return True
        return False

    def get(self, model_name: str) -> ModelPricing | None:
        """Get pricing for a model.

        Args:
            model_name: Model identifier.

        Returns:
            ModelPricing if registered, None otherwise.
        """
        return self._pricing.get(model_name)

    def get_or_fallback(self, model_name: str) -> ModelPricing | None:
        """Get pricing for a model, or fallback if not registered.

        Args:
            model_name: Model identifier.

        Returns:
            ModelPricing if registered or fallback set, None otherwise.
        """
        return self._pricing.get(model_name) or self._fallback

    def set_fallback(self, pricing: ModelPricing) -> None:
        """Set fallback pricing for unknown models.

        Args:
            pricing: ModelPricing to use as fallback.
        """
        self._fallback = pricing

    def has_pricing(self, model_name: str) -> bool:
        """Check if pricing is registered for a model.

        Args:
            model_name: Model identifier.

        Returns:
            True if registered, False otherwise.
        """
        return model_name in self._pricing

    def list_registered(self) -> list[str]:
        """List all registered model names.

        Returns:
            List of registered model identifiers.
        """
        return list(self._pricing.keys())

    def estimate_cost(self, model_name: str, token_usage: TokenUsage) -> CostEstimate | None:
        """Estimate cost for a model and token usage.

        Args:
            model_name: Model identifier.
            token_usage: Token usage to estimate cost for.

        Returns:
            CostEstimate if pricing available, None otherwise.
        """
        pricing = self.get_or_fallback(model_name)
        if pricing is None:
            return None
        return pricing.estimate_cost(token_usage)

# Stores one event that happened during execution.
class TraceEvent(BaseModel):
    """A single event in an execution trace.

    Attributes:
        id: Unique event identifier.
        event_type: Type of the trace event.
        timestamp: When the event occurred.
        execution_id: ID of the execution/trace this event belongs to.
        parent_id: Optional parent event ID for nesting.
        correlation_id: Optional correlation ID for grouping related events.
        duration_ms: Optional duration in milliseconds for completed events.
        data: Event-specific data payload (input/output metadata).
        error: Optional error information for ERROR events.
        token_usage: Optional token usage for LLM events.
        latency: Optional latency metrics.
        cost: Optional cost estimate.
        tags: Tags for filtering events.
        metadata: Additional arbitrary metadata.
    """

    id: UUID = Field(default_factory=uuid4, description="Unique event identifier")
    event_type: TraceEventType = Field(..., description="Event type")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc), description="Event timestamp"
    )
    execution_id: UUID | None = Field(None, description="Execution/trace ID this event belongs to")
    parent_id: UUID | None = Field(None, description="Parent event ID for nesting")
    correlation_id: UUID | None = Field(None, description="Correlation ID for grouping")
    duration_ms: float | None = Field(None, ge=0, description="Duration in milliseconds")
    data: dict[str, Any] = Field(default_factory=dict, description="Event data payload")
    error: str | None = Field(None, description="Error message for ERROR events")
    token_usage: TokenUsage | None = Field(None, description="Token usage for LLM events")
    latency: LatencyMetrics | None = Field(None, description="Latency metrics")
    cost: CostEstimate | None = Field(None, description="Cost estimate")
    tags: list[str] = Field(default_factory=list, description="Event tags")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Additional metadata")

    model_config = {
        "validate_assignment": True,
        "extra": "forbid",
        "use_enum_values": True,
    }

    @classmethod
    def llm_call(
        cls,
        execution_id: UUID,
        prompt: str,
        model: str,
        parent_id: UUID | None = None,
        correlation_id: UUID | None = None,
        **kwargs: Any,
    ) -> TraceEvent:
        """Create an LLM call event."""
        return cls(
            event_type=TraceEventType.LLM_CALL,
            execution_id=execution_id,
            parent_id=parent_id,
            correlation_id=correlation_id,
            data={"prompt": prompt, "model": model},
            **kwargs,
        )

    @classmethod
    def llm_response(
        cls,
        execution_id: UUID,
        response: str,
        model: str,
        token_usage: TokenUsage | None = None,
        cost: CostEstimate | None = None,
        latency: LatencyMetrics | None = None,
        parent_id: UUID | None = None,
        correlation_id: UUID | None = None,
        **kwargs: Any,
    ) -> TraceEvent:
        """Create an LLM response event."""
        return cls(
            event_type=TraceEventType.LLM_RESPONSE,
            execution_id=execution_id,
            parent_id=parent_id,
            correlation_id=correlation_id,
            data={"response": response, "model": model},
            token_usage=token_usage,
            cost=cost,
            latency=latency,
            **kwargs,
        )

    @classmethod
    def tool_call(
        cls,
        execution_id: UUID,
        tool_name: str,
        arguments: dict[str, Any],
        parent_id: UUID | None = None,
        correlation_id: UUID | None = None,
        **kwargs: Any,
    ) -> TraceEvent:
        """Create a tool call event."""
        return cls(
            event_type=TraceEventType.TOOL_CALL,
            execution_id=execution_id,
            parent_id=parent_id,
            correlation_id=correlation_id,
            data={"tool": tool_name, "arguments": arguments},
            **kwargs,
        )

    @classmethod
    def tool_response(
        cls,
        execution_id: UUID,
        tool_name: str,
        result: Any,
        parent_id: UUID | None = None,
        correlation_id: UUID | None = None,
        latency: LatencyMetrics | None = None,
        **kwargs: Any,
    ) -> TraceEvent:
        """Create a tool response event."""
        return cls(
            event_type=TraceEventType.TOOL_RESPONSE,
            execution_id=execution_id,
            parent_id=parent_id,
            correlation_id=correlation_id,
            data={"tool": tool_name, "result": result},
            latency=latency,
            **kwargs,
        )

    @classmethod
    def agent_iteration(
        cls,
        execution_id: UUID,
        iteration: int,
        action: str,
        parent_id: UUID | None = None,
        correlation_id: UUID | None = None,
        **kwargs: Any,
    ) -> TraceEvent:
        """Create an agent iteration event."""
        return cls(
            event_type=TraceEventType.AGENT_ITERATION,
            execution_id=execution_id,
            parent_id=parent_id,
            correlation_id=correlation_id,
            data={"iteration": iteration, "action": action},
            **kwargs,
        )

    @classmethod
    def execution_start(
        cls,
        execution_id: UUID,
        case_id: UUID,
        correlation_id: UUID | None = None,
        **kwargs: Any,
    ) -> TraceEvent:
        """Create an execution start event."""
        return cls(
            event_type=TraceEventType.EXECUTION_START,
            execution_id=execution_id,
            correlation_id=correlation_id,
            data={"case_id": str(case_id)},
            **kwargs,
        )

    @classmethod
    def execution_end(
        cls,
        execution_id: UUID,
        status: str,
        parent_id: UUID | None = None,
        correlation_id: UUID | None = None,
        duration_ms: float | None = None,
        **kwargs: Any,
    ) -> TraceEvent:
        """Create an execution end event."""
        return cls(
            event_type=TraceEventType.EXECUTION_END,
            execution_id=execution_id,
            parent_id=parent_id,
            correlation_id=correlation_id,
            duration_ms=duration_ms,
            data={"status": status},
            **kwargs,
        )

    @classmethod
    def create_error(
        cls,
        execution_id: UUID,
        error: str,
        parent_id: UUID | None = None,
        correlation_id: UUID | None = None,
        **kwargs: Any,
    ) -> TraceEvent:
        """Create an error event."""
        return cls(
            event_type=TraceEventType.ERROR,
            execution_id=execution_id,
            parent_id=parent_id,
            correlation_id=correlation_id,
            error=error,
            **kwargs,
        )

    def is_start_event(self) -> bool:
        """Check if this is an execution start event."""
        return self.event_type == TraceEventType.EXECUTION_START

    def is_end_event(self) -> bool:
        """Check if this is an execution end event."""
        return self.event_type == TraceEventType.EXECUTION_END

    def is_error_event(self) -> bool:
        """Check if this is an error event."""
        return self.event_type == TraceEventType.ERROR

    def get_duration_ms(self) -> float | None:
        """Get the duration in milliseconds from this event.

        Prefers latency.duration_ms if available, falls back to duration_ms field.
        Returns None if no duration information is available.
        """
        if self.latency is not None and self.latency.duration_ms is not None:
            return self.latency.duration_ms
        return self.duration_ms

    def is_llm_event(self) -> bool:
        """Check if this is an LLM-related event (call or response)."""
        return self.event_type in (TraceEventType.LLM_CALL, TraceEventType.LLM_RESPONSE)

    def is_tool_event(self) -> bool:
        """Check if this is a tool-related event (call or response)."""
        return self.event_type in (TraceEventType.TOOL_CALL, TraceEventType.TOOL_RESPONSE)

# Stores the history of one AI execution.
class ExecutionTrace(BaseModel):
    """A complete execution trace for an evaluation case.

    Attributes:
        id: Unique trace identifier.
        case_id: ID of the evaluation case this trace belongs to.
        run_id: Optional run/session identifier.
        events: Ordered list of trace events.
        start_time: Trace start timestamp.
        end_time: Trace end timestamp.
        total_tokens: Aggregated token usage.
        total_cost: Aggregated cost estimate.
        total_duration_ms: Total trace duration.
        status: Trace status (success, error, partial).
        error: Optional error message if failed.
        metadata: Additional arbitrary metadata.
    """

    id: UUID = Field(default_factory=uuid4, description="Unique trace identifier")
    case_id: UUID = Field(..., description="Evaluation case ID")
    run_id: UUID | None = Field(None, description="Run/session ID")
    events: list[TraceEvent] = Field(default_factory=list, description="Trace events")
    start_time: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc), description="Trace start time"
    )
    end_time: datetime | None = Field(None, description="Trace end time")
    total_tokens: TokenUsage = Field(
        default_factory=lambda: TokenUsage(), description="Aggregated token usage"
    )
    total_cost: CostEstimate = Field(
        default_factory=lambda: CostEstimate(
            input_cost_usd=0.0,
            output_cost_usd=0.0,
            total_cost_usd=0.0,
            model_name=None,
            pricing_version=None,
        ),
        description="Aggregated cost estimate",
    )
    total_duration_ms: float | None = Field(None, ge=0, description="Total duration")
    status: str = Field(default="in_progress", description="Trace status")
    error: str | None = Field(None, description="Error message if failed")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Trace metadata")

    def add_event(self, event: TraceEvent) -> None:
        """Add an event to the trace and update aggregates.

        Only LLM events (LLM_CALL, LLM_RESPONSE) contribute to token and cost totals.
        Tool events and other event types are recorded but do not affect aggregates.
        """
        self.events.append(event)
        if event.event_type in (TraceEventType.LLM_CALL, TraceEventType.LLM_RESPONSE):
            if event.token_usage:
                self.total_tokens += event.token_usage
            if event.cost:
                self.total_cost += event.cost

    def finalize(self, status: str = "success", error: str | None = None) -> None:
        """Mark the trace as complete."""
        self.end_time = datetime.now(timezone.utc)
        self.status = status
        self.error = error
        if self.start_time and self.end_time:
            self.total_duration_ms = (
                self.end_time - self.start_time
            ).total_seconds() * 1000

    def get_events_by_type(self, event_type: TraceEventType) -> list[TraceEvent]:
        """Get all events of a specific type."""
        return [e for e in self.events if e.event_type == event_type]

    def get_child_events(self, parent_id: UUID) -> list[TraceEvent]:
        """Get all child events of a parent event."""
        return [e for e in self.events if e.parent_id == parent_id]

    def get_llm_events(self) -> list[TraceEvent]:
        """Get all LLM-related events (calls and responses)."""
        return [
            e
            for e in self.events
            if e.event_type in (TraceEventType.LLM_CALL, TraceEventType.LLM_RESPONSE)
        ]

    def get_tool_events(self) -> list[TraceEvent]:
        """Get all tool-related events (calls and responses)."""
        return [
            e
            for e in self.events
            if e.event_type in (TraceEventType.TOOL_CALL, TraceEventType.TOOL_RESPONSE)
        ]

    def get_agent_events(self) -> list[TraceEvent]:
        """Get all agent-related events (steps, iterations, decisions)."""
        return [
            e
            for e in self.events
            if e.event_type
            in (
                TraceEventType.AGENT_STEP,
                TraceEventType.AGENT_ITERATION,
                TraceEventType.AGENT_DECISION,
            )
        ]

    def get_error_events(self) -> list[TraceEvent]:
        """Get all error events."""
        return [e for e in self.events if e.event_type == TraceEventType.ERROR]

    def get_execution_events(self) -> list[TraceEvent]:
        """Get execution start/end events."""
        return [
            e
            for e in self.events
            if e.event_type in (TraceEventType.EXECUTION_START, TraceEventType.EXECUTION_END)
        ]

    def get_root_events(self) -> list[TraceEvent]:
        """Get events with no parent (root-level events)."""
        return [e for e in self.events if e.parent_id is None]

    def get_event_tree(self) -> dict[UUID, list[TraceEvent]]:
        """Build a parent->children mapping for all events."""
        tree: dict[UUID, list[TraceEvent]] = {}
        for event in self.events:
            if event.parent_id:
                tree.setdefault(event.parent_id, []).append(event)
        return tree

    def get_llm_durations(self) -> list[float]:
        """Get durations of all LLM events (calls and responses) in milliseconds.

        Returns:
            List of duration values for LLM events that have duration information.
            Note: This includes both LLM_CALL and LLM_RESPONSE events. If both have
            duration set, they will both be counted. Use get_llm_response_durations()
            to only count response events.
        """
        durations = []
        for event in self.get_llm_events():
            duration = event.get_duration_ms()
            if duration is not None and duration >= 0:
                durations.append(duration)
        return durations

    def get_llm_response_durations(self) -> list[float]:
        """Get durations of only LLM response events in milliseconds.

        This avoids double-counting when both LLM_CALL and LLM_RESPONSE have
        duration set, since the response typically represents the complete operation.

        Returns:
            List of duration values for LLM_RESPONSE events that have duration information.
        """
        durations = []
        for event in self.get_events_by_type(TraceEventType.LLM_RESPONSE):
            duration = event.get_duration_ms()
            if duration is not None and duration >= 0:
                durations.append(duration)
        return durations

    def get_llm_response_latency_stats(self) -> LatencyStats:
        """Get aggregated latency statistics for LLM response events only.

        Returns:
            LatencyStats computed from LLM_RESPONSE event durations.
        """
        return LatencyStats.from_durations(self.get_llm_response_durations())

    def get_tool_durations(self) -> list[float]:
        """Get durations of all tool events (calls and responses) in milliseconds.

        Returns:
            List of duration values for tool events that have duration information.
        """
        durations = []
        for event in self.get_tool_events():
            duration = event.get_duration_ms()
            if duration is not None and duration >= 0:
                durations.append(duration)
        return durations

    def get_execution_wall_clock_duration_ms(self) -> float | None:
        """Get the wall-clock execution duration in milliseconds.

        This is the total duration from execution start to end (if finalized),
        or from start_time to now (if still in progress).
        This is distinct from summed operation durations.

        Returns:
            Wall-clock duration in milliseconds, or None if start_time is missing.
        """
        if self.start_time is None:
            return None
        end = self.end_time or datetime.now(timezone.utc)
        return (end - self.start_time).total_seconds() * 1000

    def get_llm_latency_stats(self) -> LatencyStats:
        """Get aggregated latency statistics for LLM events.

        Returns:
            LatencyStats computed from LLM event durations.
        """
        return LatencyStats.from_durations(self.get_llm_durations())

    def get_tool_latency_stats(self) -> LatencyStats:
        """Get aggregated latency statistics for tool events.

        Returns:
            LatencyStats computed from tool event durations.
        """
        return LatencyStats.from_durations(self.get_tool_durations())

    def get_latency_summary(self) -> dict[str, LatencyStats | float | None]:
        """Get a comprehensive latency summary for the trace.

        Returns:
            Dictionary containing:
            - llm_stats: LatencyStats for LLM events
            - tool_stats: LatencyStats for tool events
            - execution_wall_clock_ms: Wall-clock execution duration
        """
        return {
            "llm_stats": self.get_llm_latency_stats(),
            "tool_stats": self.get_tool_latency_stats(),
            "execution_wall_clock_ms": self.get_execution_wall_clock_duration_ms(),
        }

